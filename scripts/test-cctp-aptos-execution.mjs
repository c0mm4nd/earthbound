import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { Deserializer, TransactionPayload } from '@aptos-labs/ts-sdk';
import { load, intent, stellar, nativeProof } from './helpers/cctp-native-fixture.mjs';
const b = load('cctp-aptos'), scripts = load('cctp-aptos-bytecode').CCTP_APTOS_SCRIPTS;
const burn = b.cctpAptosBurnPayload(intent(9));
const restored = TransactionPayload.deserialize(new Deserializer(burn.bcsToBytes()));
assert.equal(restored.script.args[0].value, 9007199254740993n);
assert.equal(restored.script.args[5].value, 10000n);
assert.equal(restored.script.args[6].value, 2000);
assert.deepEqual(Buffer.from(restored.script.bytecode), Buffer.from(scripts.deposit_for_burn.slice(2), 'hex'));
const hook = b.cctpAptosBurnPayload(intent(9, { destinationDomain: 27, recipient: stellar }));
assert.equal(hook.script.args.length, 8);
assert.deepEqual(Buffer.from(hook.script.bytecode), Buffer.from(scripts.deposit_for_burn_with_hook.slice(2), 'hex'));
assert.throws(() => b.cctpAptosBurnPayload(intent(9, { finality: 1000 })), /finality/);
assert.throws(() => b.cctpAptosBurnPayload(intent(9, { amount: String(2n ** 64n) })), /u64/);
const p = nativeProof(9, '0x123');
const mint = b.cctpAptosClaimPayload('0x123', p.message, p.attestation);
assert.equal(mint.script.args.length, 2);
assert.deepEqual(Buffer.from(mint.script.bytecode), Buffer.from(scripts.receive_message.slice(2), 'hex'));
assert.throws(() => b.cctpAptosClaimPayload('0x456', p.message, p.attestation), /recipient/);
// Known SHA-256 values from Circle's pinned mainnet binaries, not generated by
// the transaction builder or downloaded when the test runs.
const expected = JSON.parse((await import('node:fs')).readFileSync(new URL('./fixtures/cctp-aptos-scripts.json', import.meta.url), 'utf8'));
for (const [name, hex] of Object.entries(scripts)) assert.equal(createHash('sha256').update(Buffer.from(hex.slice(2), 'hex')).digest('hex'), expected.sha256[name]);
console.log('CCTP Aptos execution: pinned mainnet scripts, BCS roundtrip, u64 precision, atomic hook/burn/mint payloads and recipient binding passed.');

const { createLoader } = await import('./helpers/load-ts.mjs');
let network = 'mainnet', account = '0x123', submits = 0;
const hash = '0x' + '01'.repeat(32), events = [];
const provider = { account: async () => ({ address: account }), network: async () => network,
  signAndSubmitTransaction: async payload => { submits++; assert.equal(payload.data, burn.script); return { hash }; } };
const executor = createLoader({}, { window: { aptos: provider } })('bridge-wallets').executeAptosUserSteps;
const step = { type: 'TRANSACTION', chainType: 'APTOS', chainKey: 'aptos', transaction: { encoded: { cctp: true, payload: { data: burn.script } } } };
await executor([step], account, undefined, { beforeSign: () => events.push('before'), submitted: h => events.push(h) });
assert.deepEqual(events, ['before', hash]);
network = 'testnet'; await assert.rejects(() => executor([step], account), /mainnet/);
network = 'mainnet'; account = '0x456'; await assert.rejects(() => executor([step], '0x123'), /wallet changed/i);
account = '0x123'; await assert.rejects(() => executor([step], account, undefined, { beforeSign() { throw Error('storage unavailable'); } }), /storage/);
assert.equal(submits, 1);
console.log('CCTP Aptos wallet: mainnet/account checks, pre-sign guard and submitted hash callback passed.');

const { createCctpMoveMonitor, CCTP_APTOS_MT } = load('cctp-move-monitor');
let chainId = 1, status = 'success', emitter = `${CCTP_APTOS_MT}::message_transmitter::MessageSent`;
const monitor = createCctpMoveMonitor(9, async (url, options) => {
  if (url.endsWith('/v1')) return Response.json({ chain_id: chainId });
  if (url.includes('/transactions/')) return status === 'missing' ? new Response('', { status: 404 }) : Response.json({ hash, type: status === 'pending' ? 'pending_transaction' : 'user_transaction', success: status === 'success', events: [{ type: emitter, data: { message: p.message } }] });
  const body = JSON.parse(options.body), name = body.function.split('::').at(-1);
  const values = { local_domain: 9, version: 1, get_signature_threshold: '1', get_num_enabled_attesters: '1', get_enabled_attester: '0x123', is_nonce_used: true };
  return Response.json([values[name]]);
});
assert.equal((await monitor.receipt(hash, true)).message, p.message);
assert.equal((await monitor.attesters()).threshold, 1);
assert.equal(await monitor.nonceUsed('0x' + '01'.repeat(32)), true);
emitter = '0x123::message_transmitter::MessageSent'; await assert.rejects(() => monitor.receipt(hash, true), /official Move/);
for (const state of ['pending', 'missing', 'failure']) { status = state; assert.equal((await monitor.receipt(hash)).state, state === 'failure' ? 'failed' : 'pending'); }
chainId = 2; await assert.rejects(() => monitor.attesters(), /mainnet/);
console.log('CCTP Aptos monitor: receipt identity, official emitter, pending/reverted receipts, mainnet and attester/nonce views passed.');
