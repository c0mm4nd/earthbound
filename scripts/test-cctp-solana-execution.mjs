import assert from 'node:assert/strict';
import { PublicKey, Keypair, TransactionMessage, VersionedTransaction } from '@solana/web3.js';
import { getAssociatedTokenAddressSync } from '@solana/spl-token';
import { createHash } from 'node:crypto';
import { load, intent, wallet, stellar, nativeProof } from './helpers/cctp-native-fixture.mjs';
import { circleCoder } from './helpers/cctp-solana-idl.mjs';
const b = load('cctp-solana'), native = load('cctp-native');
const mint = new PublicKey(load('cctp').cctpNetwork(5).usdc);
const event = Keypair.fromSeed(new Uint8Array(32).fill(7)).publicKey;
const burn = b.cctpSolanaBurnInstruction(intent(5), event);
const { coder, official } = circleCoder('token_messenger_minter_v2');
const decoded = coder.instruction.decode(burn.data);
assert.equal(decoded.name, 'depositForBurn');
assert.equal(decoded.data.params.amount.toString(), '9007199254740993');
assert.equal(decoded.data.params.maxFee.toString(), '10000');
assert.equal(decoded.data.params.destinationDomain, 0);
const accounts = official.instructions.find(i => i.name === 'deposit_for_burn').accounts;
assert.equal(burn.keys.length, accounts.length);
accounts.forEach((account, index) => {
  assert.equal(burn.keys[index].isSigner, account.signer ?? false, account.name);
  assert.equal(burn.keys[index].isWritable, account.writable ?? false, account.name);
});
assert.equal(burn.keys[11].pubkey.toBase58(), event.toBase58());
const hookBurn = b.cctpSolanaBurnInstruction(intent(5, { destinationDomain: 27, recipient: stellar }), event);
assert.equal(coder.instruction.decode(hookBurn.data).name, 'depositForBurnWithHook');
assert.throws(() => b.cctpSolanaBurnInstruction(intent(5, { amount: String(2n ** 64n) }), event), /u64/);
const target = native.cctpMintTarget(5, wallet);
assert.equal(new PublicKey(Buffer.from(target.mintRecipient.slice(2), 'hex')).toBase58(), getAssociatedTokenAddressSync(mint, new PublicKey(wallet)).toBase58());
assert.notEqual(new PublicKey(Buffer.from(target.mintRecipient.slice(2), 'hex')).toBase58(), wallet);
const p = nativeProof(5, wallet), payer = Keypair.fromSeed(new Uint8Array(32).fill(3)).publicKey;
const fee = Keypair.fromSeed(new Uint8Array(32).fill(4)).publicKey;
const instructions = b.cctpSolanaClaimInstructions(wallet, payer.toBase58(), fee, p.message, p.attestation + '11'.repeat(65));
assert.equal(instructions.length, 2);
const receive = circleCoder('message_transmitter_v2').coder.instruction.decode(instructions[1].data);
assert.equal(receive.name, 'receiveMessage');
assert.equal(receive.data.params.message.toString('hex'), p.message.slice(2));
assert.equal(instructions[1].keys[14].pubkey.toBase58(), getAssociatedTokenAddressSync(mint, fee).toBase58(), 'fee ATA must not be omitted');
const receiveAccounts = [
  ...circleCoder('message_transmitter_v2').official.instructions.find(i => i.name === 'receive_message').accounts,
  ...official.instructions.find(i => i.name === 'handle_receive_finalized_message').accounts.slice(1),
];
assert.equal(instructions[1].keys.length, receiveAccounts.length);
receiveAccounts.forEach((a, i) => {
  assert.equal(instructions[1].keys[i].isWritable, a.writable ?? false, a.name);
  assert.equal(instructions[1].keys[i].isSigner, a.signer ?? false, a.name);
});
const tx = new VersionedTransaction(new TransactionMessage({ payerKey: payer, recentBlockhash: '11111111111111111111111111111111', instructions: instructions.slice(1) }).compileToV0Message());
assert.ok(tx.serialize().length <= 1232, 'two-attester claim fits without an operator lookup table');
assert.throws(() => b.cctpSolanaClaimInstructions(payer.toBase58(), wallet, fee, p.message, p.attestation), /recipient/);
const eventData = Buffer.alloc(52 + 376);
createHash('sha256').update('account:MessageSent').digest().copy(eventData, 0, 0, 8);
eventData.writeUInt32LE(376, 48); Buffer.from(p.message.slice(2), 'hex').copy(eventData, 52);
assert.equal(b.decodeCctpSolanaEvent(eventData), p.message);
assert.throws(() => b.decodeCctpSolanaEvent(eventData.subarray(0, -1)), /length/);
assert.equal(native.isCctpNativeHash(5, '2'.repeat(88)), true);
assert.equal(native.isCctpNativeHash(5, wallet), false);
const connection = { getGenesisHash: async () => '5eykt4UsFv8P8NJdTREpY1vzqKqZKvdpKuc147dw2N9d', getLatestBlockhash: async () => ({ blockhash: '11111111111111111111111111111111', lastValidBlockHeight: 100 }) };
const built = await b.buildCctpSolanaBurn(connection, intent(5));
const signed = VersionedTransaction.deserialize(Buffer.from(built.step.transaction.encoded.serializedTransaction, 'base64'));
assert.equal(signed.message.header.numRequiredSignatures, 2);
assert.ok(signed.signatures[0].every(byte => byte === 0), 'user signature remains empty');
assert.ok(signed.signatures[1].some(byte => byte !== 0), 'event keypair is partially signed before the wallet');
await assert.rejects(() => b.buildCctpSolanaBurn({ ...connection, getGenesisHash: async () => 'devnet' }, intent(5)), /mainnet/);
console.log('CCTP Solana execution: official IDL parity, signers/account order, event signing, hooks, ATA/fee account, packet size and message-account decoding passed.');

const snapshot = JSON.parse((await import('node:fs')).readFileSync(new URL('./fixtures/cctp-solana-mainnet-state.json', import.meta.url), 'utf8'));
const mt = Buffer.from(snapshot.accounts.transmitter.data, 'base64');
assert.equal(b.decodeCctpSolanaAttesters(mt).threshold, 2);
assert.equal(b.decodeCctpSolanaAttesters(mt).enabledAttesters.length, 2);
assert.equal(b.decodeCctpSolanaMessenger(Buffer.from(snapshot.accounts.messenger.data, 'base64')).feeRecipient.toBase58(), '4BPnUzFDibVcWQ5zzixGodRUHwqDxHYpUPdPYus3Bn56');
const paused = Buffer.from(mt); paused[136] = 1;
assert.throws(() => b.decodeCctpSolanaAttesters(paused), /paused/);
await assert.rejects(() => b.readCctpSolanaAttesters({ ...connection, getAccountInfo: async () => ({ owner: new PublicKey(wallet), data: mt }) }), /unavailable/);
const nonceData = Buffer.concat([createHash('sha256').update('account:UsedNonce').digest().subarray(0, 8), Buffer.from([1])]);
assert.equal(await b.readCctpSolanaNonce({ ...connection, getAccountInfo: async () => null }, '0x' + '01'.repeat(32)), false);
assert.equal(await b.readCctpSolanaNonce({ ...connection, getAccountInfo: async () => ({ owner: b.SOLANA_CCTP_MT, data: nonceData }) }, '0x' + '01'.repeat(32)), true);
await assert.rejects(() => b.readCctpSolanaNonce({ ...connection, getAccountInfo: async () => ({ owner: b.SOLANA_CCTP_TMM, data: nonceData }) }, '0x' + '01'.repeat(32)), /Invalid/);
const fakeReceipt = { transaction: { signatures: ['2'.repeat(88)], message: signed.message }, meta: { err: null, loadedAddresses: { writable: [], readonly: [] } } };
const source = intent(5), wire = load('cctp-native-proof'), { pad, toHex } = await import('viem');
const raw = Buffer.alloc(376); raw.writeUInt32BE(1, 0); raw.writeUInt32BE(5, 4); raw.writeUInt32BE(2000, 140); raw.writeUInt32BE(1, 148);
for (const [offset, hex] of [[44, wire.cctpWireMessenger(5)], [76, wire.cctpWireMessenger(0)], [152, wire.cctpWireUsdc(5)],
  [184, pad(source.recipient)], [216, pad(toHex(BigInt(source.amount)))], [248, wire.cctpWireAddress(5, source.sender)], [280, pad(toHex(BigInt(source.maxFee)))]]) Buffer.from(hex.slice(2), 'hex').copy(raw, offset);
const sourceEvent = Buffer.from(eventData); raw.copy(sourceEvent, 52);
const rpc = { ...connection, getTransaction: async () => fakeReceipt, getAccountInfo: async () => ({ owner: b.SOLANA_CCTP_MT, data: sourceEvent }) };
assert.equal((await b.readCctpSolanaBurn(rpc, source, '2'.repeat(88), built.eventAccount)).state, 'confirmed');
await assert.rejects(() => b.readCctpSolanaBurn(rpc, source, '2'.repeat(88), wallet), /reviewed/);
await assert.rejects(() => b.readCctpSolanaBurn(rpc, { ...source, amount: '12345' }, '2'.repeat(88), built.eventAccount), /reviewed/);
assert.equal((await b.readCctpSolanaBurn({ ...rpc, getTransaction: async () => null }, source, '2'.repeat(88), built.eventAccount)).state, 'pending');
console.log('CCTP Solana monitor: real mainnet state decoding, attester/paused checks, nonce owner checks and exact source-instruction/message-account binding passed.');
